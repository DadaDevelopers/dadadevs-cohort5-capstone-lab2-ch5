const express = require("express");
const authenticate = require("../middleware/auth.middleware");
const limits = require("../middleware/auth-rate-limit");
const communityLimiter = limits.communityLimiter || limits.authLimiter;
const financialLimiter = limits.financialLimiter || communityLimiter;
const discussionLimiter = limits.discussionLimiter || communityLimiter;
const controller = require("../controllers/community.controller");
const memberController = require("../controllers/community-members.controller");
const signerController = require("../controllers/community-signers.controller");
const publicInfoController = require("../controllers/signer-public-info.controller");
const thresholdController = require("../controllers/signing-threshold.controller");
const walletController = require("../controllers/wallet.controller");
const activityController = require("../controllers/activity.controller");

const router = express.Router();

const protectedRoute = [authenticate, communityLimiter];
const financialRoute = [authenticate, communityLimiter, financialLimiter];

router.post("/", ...protectedRoute, controller.create);
router.post("/join", ...protectedRoute, controller.join);
router.get("/", ...protectedRoute, controller.list);
router.get("/:identifier", ...protectedRoute, controller.get);
router.get("/:communityId/audit-events", ...protectedRoute, activityController.audit);
router.get("/:communityId/notifications", ...protectedRoute, activityController.notifications);
router.get("/:communityId/notifications/unread-count", ...protectedRoute, activityController.unread);
router.patch("/:communityId/notifications/:notificationId/read", ...protectedRoute, activityController.read);
router.post("/:communityId/notifications/read-all", ...protectedRoute, activityController.readAll);
router.get("/:communityId/members", ...protectedRoute, controller.members);
router.post("/:communityId/members", ...protectedRoute, memberController.add);
router.patch("/:communityId/members/:userId/role", ...protectedRoute, memberController.changeRole);
router.delete("/:communityId/members/:userId", ...protectedRoute, memberController.remove);
router.post("/:communityId/signers", ...protectedRoute, signerController.select);
router.get("/:communityId/signers", ...protectedRoute, signerController.list);
router.delete("/:communityId/signers/:userId", ...protectedRoute, signerController.remove);
router.put("/:communityId/signers/me/public-info", ...protectedRoute, publicInfoController.put);
router.get("/:communityId/signers/me/public-info", ...protectedRoute, publicInfoController.get);
router.put("/:communityId/signing-threshold", ...protectedRoute, thresholdController.put);
router.get("/:communityId/signing-threshold", ...protectedRoute, thresholdController.get);
router.post("/:communityId/wallet", ...financialRoute, walletController.create);
router.get("/:communityId/wallet", ...protectedRoute, walletController.get);
router.get("/:communityId/wallet/balance", ...protectedRoute, walletController.balance);
router.get("/:communityId/wallet/utxos", ...protectedRoute, walletController.utxos);
router.get("/:communityId/wallet/transactions", ...protectedRoute, walletController.transactions);
router.get("/:communityId/wallet/transactions/:txid", ...protectedRoute, walletController.transaction);
router.post("/:communityId/wallet/spends", ...financialRoute, walletController.createSpend);
router.get("/:communityId/wallet/spends", ...protectedRoute, walletController.listSpends);
router.get("/:communityId/wallet/spends/:spendId", ...protectedRoute, walletController.getSpend);
router.get("/:communityId/wallet/spends/:spendId/psbt", ...protectedRoute, walletController.psbt);
router.get("/:communityId/wallet/spends/:spendId/discussion", ...protectedRoute, activityController.discussion);
router.post("/:communityId/wallet/spends/:spendId/discussion", ...protectedRoute, discussionLimiter, activityController.addMessage);
router.post("/:communityId/wallet/spends/:spendId/signatures", ...financialRoute, walletController.sign);
router.post("/:communityId/wallet/spends/:spendId/broadcast", ...financialRoute, walletController.broadcast);
router.post("/:communityId/wallet/spends/:spendId/cancel", ...financialRoute, walletController.cancelSpend);

module.exports = router;
